    private final Random random;
    private final String[][] decks=new String[Moment.values().length][];
    private final int[] cursor=new int[decks.length];

    PetRemarks(Random random){this.random=random;}

    String draw(Moment moment){
        int index=moment.ordinal();
        String[] deck=decks[index];
        if(deck==null||cursor[index]==deck.length){
            String last=deck==null?null:deck[deck.length-1];
            deck=moment.lines.clone();
            for(int i=deck.length-1;i>0;i--)swap(deck,i,random.nextInt(i+1));
            if(deck[0].equals(last))swap(deck,0,1+random.nextInt(deck.length-1));
            decks[index]=deck;
            cursor[index]=0;
        }
        return deck[cursor[index]++];
    }

    private static void swap(String[] deck,int i,int j){
        String line=deck[i];
        deck[i]=deck[j];
        deck[j]=line;
    }
