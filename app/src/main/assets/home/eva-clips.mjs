// Monotone cubic tangents preserve a resting hand when two consecutive keys
// share its coordinates. Periodic neighbours give the loop a continuous speed.
function compile({seconds,space,keys}){
 const count=Math.round(seconds*EVA_FPS),stride=keys[0].value.length;
 const frames=new Float32Array(count*stride);
 const at=i=>keys[(i+keys.length)%keys.length];
 const interval=(a,b)=>(b.phase-a.phase+1)%1;
 function tangent(i,axis){
   const a=at(i-1),b=at(i),c=at(i+1);
   const left=(b.value[axis]-a.value[axis])/interval(a,b);
   const right=(c.value[axis]-b.value[axis])/interval(b,c);
   return left*right<=0?0:2*left*right/(left+right);
 }
 let segment=0;
 for(let frame=0;frame<count;frame++){
   const phase=frame/count;
   while(segment+1<keys.length&&keys[segment+1].phase<=phase)segment++;
   const a=at(segment),b=at(segment+1),h=interval(a,b);
   const t=(phase-a.phase)/h,t2=t*t,t3=t2*t;
   for(let axis=0;axis<stride;axis++)frames[frame*stride+axis]=
     (2*t3-3*t2+1)*a.value[axis]+(t3-2*t2+t)*h*tangent(segment,axis)+
     (-2*t3+3*t2)*b.value[axis]+(t3-t2)*h*tangent(segment+1,axis);
 }
 return {count,stride,space,frames};
}
export const evaClips=Object.fromEntries(Object.entries(source).map(([name,spec])=>[name,compile(spec)]));
export function evaClipFrame(name,seconds,reduced=false){
 const clip=evaClips[name]||evaClips.idle;
 const index=reduced?Math.floor(clip.count*.36):((Math.floor(seconds*EVA_FPS)%clip.count)+clip.count)%clip.count;
 const i=index*clip.stride,v=clip.frames;
 return {right:[v[i],v[i+1],v[i+2]],left:[v[i+3],v[i+4],v[i+5]],
   lean:v[i+6],look:v[i+7],tilt:v[i+8],weight:v[i+9],space:clip.space,index};
}
