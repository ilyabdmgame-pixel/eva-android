const decks=new Map();
export function remark(moment){
  let deck=decks.get(moment);
  if(!deck||deck.index===deck.lines.length){
    const lines=[...cards[moment]];
    const last=deck?.lines.at(-1);
    for(let i=lines.length-1;i>0;i--){
      const j=Math.floor(Math.random()*(i+1));[lines[i],lines[j]]=[lines[j],lines[i]];
    }
    if(last&&lines[0]===last)[lines[0],lines[1]]=[lines[1],lines[0]];
    deck={lines,index:0};decks.set(moment,deck);
  }
  return deck.lines[deck.index++];
}
