export function createCitizens(slot){
  return people.map((model,index)=>{
    const i=(slot+index)%model.spots.length;
    const [sector,u,v,doing]=model.spots[i];
    return {...model,...worldPoint(sector,u,v),doing,index:i,wait:0,journey:[],stride:0,speed:0,yieldUntil:0,direction:'down-right',talking:0,noticed:false};
  });
}
export function dialogue(person,index,context){
  const street=streetDialogue(person,index,context);if(street)return street;
  if(person.key==='mio'&&context.bucket&&context.sector==='shop'&&index%3===0){
    return index%2?['Ведро сменило адрес. Ты хоть переадресацию оформила?','Ведро теперь напольная ваза.']:
      ['Стою с цветами и без ведра. Кто опять интерьер оптимизирует?','Ладно, у уборки есть побочные эффекты.'];
  }
  return decks[person.key][index%decks[person.key].length];
}
